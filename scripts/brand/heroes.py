    t = math.pi * k / 40
    a = (cx - math.cos(t) * rx, G - math.sin(t) * ry); b = (cx - math.cos(t) * (rx - 40), G - math.sin(t) * (ry - 34))
    t2 = math.pi * (k + 1) / 40; c = (cx - math.cos(t2) * (rx - 40), G - math.sin(t2) * (ry - 34))
    d.p(f'M{a[0]:.0f} {a[1]:.0f}L{b[0]:.0f} {b[1]:.0f}L{c[0]:.0f} {c[1]:.0f}', .3)
