# 06 · Isometric tower in wireframe
d = D(); d.ground('TOWER · ISOMETRIC 1:500')
def iso(x, y, z): return 900 + (x - y) * 0.866, G - 30 - (x + y) * 0.5 - z
for gx in range(-10, 11): a = iso(gx * 60, -600, 0); b = iso(gx * 60, 600, 0); d.p(f'M{a[0]:.0f} {a[1]:.0f}L{b[0]:.0f} {b[1]:.0f}', .06)
for gy in range(-10, 11): a = iso(-600, gy * 60, 0); b = iso(600, gy * 60, 0); d.p(f'M{a[0]:.0f} {a[1]:.0f}L{b[0]:.0f} {b[1]:.0f}', .06)
def box(x0, y0, sx, sy, z0, z1, op=.55, step=24):
    pts = [(x0, y0), (x0 + sx, y0), (x0 + sx, y0 + sy), (x0, y0 + sy)]
    for z in (z0, z1):
        q = [iso(px, py, z) for px, py in pts]; d.p('M' + 'L'.join(f'{a:.0f} {b:.0f}' for a, b in q) + 'Z', op, 1.2)
    for px, py in pts: a = iso(px, py, z0); b = iso(px, py, z1); d.p(f'M{a[0]:.0f} {a[1]:.0f}L{b[0]:.0f} {b[1]:.0f}', op)
    z = z0 + step
    while z < z1:
        q = [iso(px, py, z) for px, py in pts[:3]]; d.p('M' + 'L'.join(f'{a:.0f} {b:.0f}' for a, b in q), op * .3); z += step
box(-120, -120, 240, 240, 0, 180); box(-90, -90, 180, 180, 180, 360); box(-60, -60, 120, 120, 360, 470)
box(200, -260, 160, 160, 0, 120, .35); box(-380, 180, 140, 200, 0, 90, .3)
t = iso(0, 0, 470); d.p(f'M{t[0]:.0f} {t[1]:.0f}V{t[1] - 70:.0f}', .5); d.c(t[0], t[1] - 74, 3, fill=True)
d.save(6, 'an isometric wireframe tower')

