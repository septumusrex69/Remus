"""Remus · Handover 6: hero drawings 03-10 for Platinum Night (Stephan: "Give me like 10 options to choose from").
Silver line drawings on nothing, 1800 x 640, ground line at y=560. Run: python3 scripts/brand/heroes.py"""
import math, os, random
W, H, G = 1800, 640, 560
OUT = os.path.join(os.path.dirname(__file__), '../../public/brand/heroes')

class D:
    def __init__(s): s.o = []; s.t = []
    def p(s, d, op=.6, w=1, dash=None): s.o.append(f'<path d="{d}" stroke-opacity="{op}" stroke-width="{w}"' + (f' stroke-dasharray="{dash}"' if dash else '') + '/>')
    def c(s, x, y, r, op=.5, fill=False): s.o.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" stroke-opacity="{op}"' + (' fill="#e6e8eb" fill-opacity=".9" stroke="none"' if fill else '') + '/>')
    def txt(s, x, y, t, size=10, op=.55, anchor='start'): s.t.append(f'<text x="{x}" y="{y}" font-size="{size}" fill-opacity="{op}" text-anchor="{anchor}">{t}</text>')
    def ground(s, label):
        s.p(f'M0 {G}H{W}', .7, 1.4)
        for k, y in enumerate([G + 10, G + 24, G + 44]): s.p(f'M0 {y}H{W}', .05 + .01 * k)
        s.txt(40, G + 46, label)
    def save(s, n, note):
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <!-- Remus · Handover 6, hero {n:02d}: {note}. Generated by scripts/brand/heroes.py. -->
  <g fill="none" stroke="#c4c8cf" stroke-linecap="square">
{chr(10).join(s.o)}
  </g>
  <g fill="#c4c8cf" font-family="Inter, Arial, sans-serif" letter-spacing="2">
{chr(10).join(s.t)}
  </g>
</svg>'''
        open(os.path.join(OUT, f'hero-{n:02d}.svg'), 'w').write(svg)

def floors(d, x, w, top, step, op=.25):
    y = G - step
    while y > top: d.p(f'M{x} {y}H{x + w}', op); y -= step

def crane(d, x, h, left, right, op=.55):
    d.p(f'M{x} {G}V{G - h}M{x + 10} {G}V{G - h}', op, 1.2)
    for k in range(int(h / 20)): d.p(f'M{x} {G - k * 20}L{x + 10} {G - k * 20 - 20}', op * .45)
    d.p(f'M{x - left} {G - h}H{x + right}M{x - left} {G - h + 12}H{x + right}', op, 1.1)
    for k in range(int((left + right) / 20)): xx = x - left + k * 20; d.p(f'M{xx} {G - h + 12}L{xx + 10} {G - h}L{xx + 20} {G - h + 12}', op * .4)
    d.p(f'M{x + 5} {G - h}V{G - h - 50}L{x + right} {G - h}M{x + 5} {G - h - 50}L{x - left} {G - h}', op * .7)

