"""Remus · Handover 6: contour heroes 11-18 for Platinum Night (Stephan: "The only one ... I actually like was the last
one. That contours thing"). Real contours of a made-up terrain (sum of hills), traced by marching squares, with a
different site story on each. Run: python3 scripts/brand/heroes_contours.py"""
import math, os, random
W, H = 1800, 640
OUT = os.path.join(os.path.dirname(__file__), '../../public/brand/heroes')
CELL = 8

def field(hills):
    def z(x, y):
        return sum(a * math.exp(-(((x - cx) / sx) ** 2 + ((y - cy) / sy) ** 2)) for cx, cy, sx, sy, a in hills) + 0.00012 * x
    return z

def contours(z, levels):
    nx, ny = W // CELL + 1, H // CELL + 1
    g = [[z(i * CELL, j * CELL) for i in range(nx)] for j in range(ny)]
    out = {}
    for lv in levels:
        segs = []
        for j in range(ny - 1):
            for i in range(nx - 1):
                a, b, c, d = g[j][i], g[j][i + 1], g[j + 1][i + 1], g[j + 1][i]
                pts = []
                for (p, q, x1, y1, x2, y2) in [(a, b, i, j, i + 1, j), (b, c, i + 1, j, i + 1, j + 1), (c, d, i + 1, j + 1, i, j + 1), (d, a, i, j + 1, i, j)]:
                    if (p - lv) * (q - lv) < 0:
                        t = (lv - p) / (q - p)
                        pts.append(((x1 + (x2 - x1) * t) * CELL, (y1 + (y2 - y1) * t) * CELL))
                if len(pts) >= 2: segs.append((pts[0], pts[1]))
                if len(pts) == 4: segs.append((pts[2], pts[3]))
        out[lv] = segs
    return out

class D:
    def __init__(s): s.o = []; s.t = []
    def p(s, d, op=.5, w=1, dash=None): s.o.append(f'<path d="{d}" stroke-opacity="{op}" stroke-width="{w}"' + (f' stroke-dasharray="{dash}"' if dash else '') + '/>')
    def c(s, x, y, r, op=.5, fill=False): s.o.append(f'<circle cx="{x:.0f}" cy="{y:.0f}" r="{r}" stroke-opacity="{op}"' + (' fill="#e6e8eb" fill-opacity=".9" stroke="none"' if fill else '') + '/>')
    def txt(s, x, y, t, size=10, op=.55, anchor='start'): s.t.append(f'<text x="{x:.0f}" y="{y:.0f}" font-size="{size}" fill-opacity="{op}" text-anchor="{anchor}">{t}</text>')
    def topo(s, z, lo, hi, step, major=5, op=.13, opmaj=.32):
        n = 0; lv = lo
        cs = contours(z, [lo + k * step for k in range(int((hi - lo) / step) + 1)])
        for k, (lv, segs) in enumerate(sorted(cs.items())):
            d = ''.join(f'M{a[0]:.0f} {a[1]:.0f}L{b[0]:.0f} {b[1]:.0f}' for a, b in segs)
            if d: s.p(d, opmaj if k % major == 0 else op, 1.2 if k % major == 0 else 1)
    def grid(s, step=150, op=.05):
        for x in range(0, W, step): s.p(f'M{x} 0V{H}', op)
        for y in range(0, H, step): s.p(f'M0 {y}H{W}', op)
    def save(s, n, note):
        svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <!-- Remus · Handover 6, hero {n:02d}: {note}. Generated by scripts/brand/heroes_contours.py. -->
  <g fill="none" stroke="#c4c8cf" stroke-linecap="round">
{chr(10).join(s.o)}
  </g>
  <g fill="#c4c8cf" font-family="Inter, Arial, sans-serif" letter-spacing="2">
{chr(10).join(s.t)}
  </g>
</svg>'''
        open(os.path.join(OUT, f'hero-{n:02d}.svg'), 'w').write(svg)

